// train.py 와 app.py 의 같은 이름 상수와 반드시 같아야 한다.
export const 평균 = 0.1307;
export const 표준편차 = 0.3081;

/** float16 비트 하나를 배정밀도 수로 바꾼다. */
function 반정밀도값(비트) {
  const 부호 = (비트 & 0x8000) ? -1 : 1;
  const 지수 = (비트 >> 10) & 0x1f;
  const 가수 = 비트 & 0x03ff;
  if (지수 === 0) return 부호 * 6.103515625e-5 * (가수 / 1024);  // 비정규값
  if (지수 === 31) return 가수 ? NaN : 부호 * Infinity;
  return 부호 * Math.pow(2, 지수 - 15) * (1 + 가수 / 1024);
}

/**
 * 가중치.bin 의 한 구간을 float32 배열로 푼다.
 * DataView.getFloat16 은 아직 새 문법이라 쓰지 않고 직접 푼다.
 */
export function 반정밀도_해독(버퍼, 오프셋, 개수) {
  const 뷰 = new DataView(버퍼);
  const 결과 = new Float32Array(개수);
  for (let i = 0; i < 개수; i++) {
    결과[i] = 반정밀도값(뷰.getUint16(오프셋 + i * 2, true));  // 리틀엔디언
  }
  return 결과;
}

/** 가중치_구조.json 을 보고 가중치.bin 을 층별 배열로 나눈다. */
export function 가중치_펼치기(버퍼, 구조) {
  const 가중치들 = {};
  for (const 층 of 구조.층목록) {
    가중치들[층.이름] = 반정밀도_해독(버퍼, 층.오프셋, 층.개수);
  }
  return 가중치들;
}

/**
 * 3x3 합성곱. 채우기 없음, 보폭 1 이라 크기가 2 줄어든다.
 * 입력과 출력 모두 채널 우선(채널 -> 행 -> 열) 순서다.
 */
export function 합성곱3x3(입력, 입력채널, 입력크기, 가중치, 편향, 출력채널) {
  const 출력크기 = 입력크기 - 2;
  const 결과 = new Float32Array(출력채널 * 출력크기 * 출력크기);
  const 입력면 = 입력크기 * 입력크기;
  for (let 출채 = 0; 출채 < 출력채널; 출채++) {
    const 출바닥 = 출채 * 출력크기 * 출력크기;
    const 편 = 편향[출채];
    for (let y = 0; y < 출력크기; y++) {
      for (let x = 0; x < 출력크기; x++) {
        let 합 = 편;  // 누적은 배정밀도로 한다
        for (let 입채 = 0; 입채 < 입력채널; 입채++) {
          const ㅂ = 입채 * 입력면 + y * 입력크기 + x;
          const ㄱ = (출채 * 입력채널 + 입채) * 9;
          합 += 입력[ㅂ] * 가중치[ㄱ]
             + 입력[ㅂ + 1] * 가중치[ㄱ + 1]
             + 입력[ㅂ + 2] * 가중치[ㄱ + 2]
             + 입력[ㅂ + 입력크기] * 가중치[ㄱ + 3]
             + 입력[ㅂ + 입력크기 + 1] * 가중치[ㄱ + 4]
             + 입력[ㅂ + 입력크기 + 2] * 가중치[ㄱ + 5]
             + 입력[ㅂ + 2 * 입력크기] * 가중치[ㄱ + 6]
             + 입력[ㅂ + 2 * 입력크기 + 1] * 가중치[ㄱ + 7]
             + 입력[ㅂ + 2 * 입력크기 + 2] * 가중치[ㄱ + 8];
        }
        결과[출바닥 + y * 출력크기 + x] = 합;
      }
    }
  }
  return 결과;
}

/** 음수를 0 으로 만든다. 자리를 새로 잡지 않고 그대로 고친다. */
export function 렐루_제자리(배열) {
  for (let i = 0; i < 배열.length; i++) if (배열[i] < 0) 배열[i] = 0;
  return 배열;
}

/** 2x2 최대 풀링, 보폭 2. 크기가 절반이 된다. */
export function 최대풀링2(입력, 채널, 입력크기) {
  const 출력크기 = 입력크기 >> 1;
  const 결과 = new Float32Array(채널 * 출력크기 * 출력크기);
  for (let 채 = 0; 채 < 채널; 채++) {
    const 입바닥 = 채 * 입력크기 * 입력크기;
    const 출바닥 = 채 * 출력크기 * 출력크기;
    for (let y = 0; y < 출력크기; y++) {
      for (let x = 0; x < 출력크기; x++) {
        const ㅂ = 입바닥 + (y * 2) * 입력크기 + x * 2;
        const a = 입력[ㅂ], b = 입력[ㅂ + 1];
        const c = 입력[ㅂ + 입력크기], d = 입력[ㅂ + 입력크기 + 1];
        결과[출바닥 + y * 출력크기 + x] = Math.max(Math.max(a, b), Math.max(c, d));
      }
    }
  }
  return 결과;
}

/** 완전연결. 가중치는 [출력개수, 입력개수] 행 우선이다. */
export function 완전연결(입력, 가중치, 편향, 출력개수) {
  const 입력개수 = 입력.length;
  const 결과 = new Float32Array(출력개수);
  for (let o = 0; o < 출력개수; o++) {
    const 바닥 = o * 입력개수;
    let 합 = 편향[o];
    for (let i = 0; i < 입력개수; i++) 합 += 입력[i] * 가중치[바닥 + i];
    결과[o] = 합;
  }
  return 결과;
}

/** 최댓값을 빼고 계산해 수치적으로 안정한 소프트맥스. */
export function 소프트맥스(로짓) {
  let 최대 = 로짓[0];
  for (let i = 1; i < 로짓.length; i++) if (로짓[i] > 최대) 최대 = 로짓[i];
  const 결과 = new Float32Array(로짓.length);
  let 합 = 0;
  for (let i = 0; i < 로짓.length; i++) {
    const 값 = Math.exp(로짓[i] - 최대);
    결과[i] = 값;
    합 += 값;
  }
  for (let i = 0; i < 결과.length; i++) 결과[i] /= 합;
  return 결과;
}

/**
 * 28x28 화소(0~255)를 넣어 숫자 0~9 의 확률을 얻는다.
 * app.py 의 확률_계산 과 같은 일을 한다.
 */
export function 확률_계산(가중치들, 화소28) {
  if (화소28.length !== 784) throw new Error(`28x28 이 아닙니다: ${화소28.length}`);

  // 0~255 를 0~1 로 바꾸고 학습 때와 같은 정규화를 적용한다.
  const 입력 = new Float32Array(784);
  for (let i = 0; i < 784; i++) 입력[i] = (화소28[i] / 255 - 평균) / 표준편차;

  let 값 = 합성곱3x3(입력, 1, 28, 가중치들["conv1.weight"], 가중치들["conv1.bias"], 32);
  렐루_제자리(값);                                   // 32 x 26 x 26
  값 = 합성곱3x3(값, 32, 26, 가중치들["conv2.weight"], 가중치들["conv2.bias"], 64);
  렐루_제자리(값);                                   // 64 x 24 x 24
  값 = 최대풀링2(값, 64, 24);                        // 64 x 12 x 12 = 9216

  // 파이썬의 flatten(1) 은 채널 우선으로 편다. 위 배열이 이미 그 순서라 할 일이 없다.
  값 = 완전연결(값, 가중치들["fc1.weight"], 가중치들["fc1.bias"], 128);
  렐루_제자리(값);
  값 = 완전연결(값, 가중치들["fc2.weight"], 가중치들["fc2.bias"], 10);
  return 소프트맥스(값);
}
